                   // ---LOGICAL OPERATORS ---

const temp = 0;

//AND OPERATOR
if(temp>0 && temp ==0){
    console.log("weather is good");
}
//OR OPERATOR
else if(temp<=30 || temp==40){
    console.log("weather is average");
}
//NOT OPERATOR
else if(temp !=50){
    console.log("weather is still good");
}
else{
    console.log("weather is bad");
}